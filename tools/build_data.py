"""Builds ../data/sky-data.js from the d3-celestial catalog files in ../raw.

Source: https://github.com/ofrohn/d3-celestial (BSD-3-Clause), data derived from
the Hipparcos / Yale Bright Star catalogs (J2000.0 equatorial coordinates).
Run:  python tools/build_data.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RAW = os.path.join(HERE, "..", "raw")
OUT = os.path.join(HERE, "..", "data", "sky-data.js")


def load(name):
    with open(os.path.join(RAW, name), encoding="utf8") as f:
        return json.load(f)


def ra360(lon):
    return round(lon + 360 if lon < 0 else lon, 4)


stars_src = load("stars.6.json")["features"]
names_src = load("starnames.json")
const_src = load("constellations.json")["features"]
lines_src = load("constellations.lines.json")["features"]

stars = []  # [ra, dec, mag, bv, name, designation]
for f in stars_src:
    ra, dec = f["geometry"]["coordinates"]
    p = f["properties"]
    try:
        bv = round(float(p.get("bv") or 0.6), 3)
    except ValueError:
        bv = 0.6
    n = names_src.get(str(f["id"]), {})
    desig = ""
    if n.get("c"):
        d = n.get("bayer") or n.get("flam") or ""
        if d:
            desig = d + " " + n["c"]
    stars.append([ra360(ra), round(dec, 4), p["mag"], bv, n.get("name", ""), desig])

stars.sort(key=lambda s: s[2])  # brightest first (drawn last / labelled first)

constellations = []
for f in const_src:
    lon, lat = f["geometry"]["coordinates"]
    constellations.append({"id": f["id"], "name": f["properties"]["name"],
                           "rank": int(f["properties"]["rank"]),
                           "ra": ra360(lon), "dec": lat})

lines = []
for f in lines_src:
    for seg in f["geometry"]["coordinates"]:
        lines.append([[ra360(a), round(b, 4)] for a, b in seg])

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w", encoding="utf8") as f:
    f.write("// Generated by tools/build_data.py - do not edit.\n")
    f.write("// Star data: d3-celestial (BSD-3-Clause), Hipparcos/YBS, J2000.0.\n")
    f.write("window.SKY_DATA = ")
    json.dump({"stars": stars, "constellations": constellations, "lines": lines},
              f, ensure_ascii=False, separators=(",", ":"))
    f.write(";\n")

print(f"stars={len(stars)} named={sum(1 for s in stars if s[4])} "
      f"constellations={len(constellations)} line_segments={len(lines)} -> {OUT}")
