"""Builds artifact/index.html: the web-hosted version of Sky Viewer.

The Claude artifact host wraps a page in its own <!doctype>/<head>/<body>, so this
script takes index.html and keeps only the <title>, the stylesheet link and the
body content. Scripts and styles stay as separate files, published alongside the
page with the same relative paths (css/, js/, data/, vendor/).

Run:  python tools/build_artifact.py
Then publish artifact/index.html with those folders as supporting files.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
SRC = os.path.join(ROOT, "index.html")
OUT = os.path.join(ROOT, "artifact", "index.html")

html = open(SRC, encoding="utf8").read()

title = re.search(r"<title>.*?</title>", html, re.S).group(0)
links = "\n".join(re.findall(r"<link [^>]*>", html))
body = re.search(r"<body[^>]*>(.*)</body>", html, re.S).group(1).strip()

# Links back to the other places the project lives, shown in the Help dialog.
body = body.replace(
    '<p class="small">Positions come from',
    '<p class="small">Sky Viewer is open source: '
    '<a href="https://github.com/jamesallenohio513/sky-viewer" target="_blank" rel="noopener">source code on GitHub</a> · '
    '<a href="https://youtu.be/L6EY8SLfnvI" target="_blank" rel="noopener">demo video</a> · '
    '<a href="https://claude.ai/artifact/W9cEwXDT2jRrDYgySSYuDF" target="_blank" rel="noopener">build report</a>. '
    'In this web version, "Use my current location" is unavailable, so search for a city or type coordinates instead.</p>\n'
    '    <p class="small">Positions come from',
    1,
)
assert "source code on GitHub" in body, "help-dialog anchor text changed; update build_artifact.py"

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w", encoding="utf8", newline="\n") as f:
    f.write("<!-- Generated by tools/build_artifact.py from index.html - do not edit. -->\n")
    f.write(title + "\n" + links + "\n" + body + "\n")
print("wrote", OUT, os.path.getsize(OUT), "bytes")
